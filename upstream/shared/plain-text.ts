// 把 Markdown 收成一行纯文字：首页列表的预览、引用条、推送通知都用它，不显示 ** # ` 这些记号。
// 只去记号、留内容；蛇形命名里的下划线（snake_case）这种不在词边上的不动。

export function plainText(md: string): string {
  return (
    md
      // 代码块：留代码，去围栏和语言名
      .replace(/```[^\n]*\n?([\s\S]*?)```/g, "$1")
      // 图片留说明文字，链接留链接文字
      .replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1")
      .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
      // 行首：标题、引用、列表记号、任务框
      .replace(/^[ \t]*#{1,6}[ \t]+/gm, "")
      .replace(/^[ \t]*>[ \t]?/gm, "")
      .replace(/^[ \t]*(?:[-*+]|\d+[.)])[ \t]+(?:\[[ xX]\][ \t]+)?/gm, "")
      // 表格：分隔行整行去掉，竖线换成空格
      .replace(/^[ \t]*\|?[ \t]*:?-{3,}:?[ \t]*(?:\|[ \t]*:?-{3,}:?[ \t]*)*\|?[ \t]*$/gm, "")
      .replace(/[ \t]*\|[ \t]*/g, " ")
      // 分隔线
      .replace(/^[ \t]*(?:[-*_][ \t]*){3,}$/gm, "")
      // 粗体、斜体、删除线、行内代码
      .replace(/(\*\*|__)(?=\S)([\s\S]*?\S)\1/g, "$2")
      .replace(/~~(?=\S)([\s\S]*?\S)~~/g, "$1")
      .replace(/(^|[^\w*])\*(?=\S)([^*\n]*?\S)\*(?![\w*])/g, "$1$2")
      .replace(/(^|[^\w])_(?=\S)([^_\n]*?\S)_(?!\w)/g, "$1$2")
      .replace(/`([^`\n]+)`/g, "$1")
      // 多行收成一行
      .replace(/\s+/g, " ")
      .trim()
  );
}
