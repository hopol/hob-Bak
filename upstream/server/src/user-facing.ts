let patterns: { key: string; re: RegExp; names: string[] }[] | undefined;

function compile(): NonNullable<typeof patterns> {
  return ERRORS.map((key) => {
    const names: string[] = [];
    const parts = key.split(/(\{[A-Za-z][A-Za-z0-9_]*\})/);
    const source = parts.map((part, i) => {
      const name = /^\{(.+)\}$/.exec(part)?.[1];
      if (!name) return part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      names.push(name);
      // 末尾的占位符可以是空的，比如服务商返回状态码后面没有补充说明
      return parts.slice(i + 1).some((next) => next !== "") ? "(.+?)" : "(.*?)";
    }).join("");
    return { key, re: new RegExp(`^${source}$`, "s"), names };
  // 字面部分长的先试：「生成失败：接口未返回图片：…」要排在「生成失败：…」前面
  }).sort((a, b) => b.key.replace(/\{[^}]+\}/g, "").length - a.key.replace(/\{[^}]+\}/g, "").length);
}

/** 把中文原文的错误翻成界面语言；认不出的原样返回（比如服务商自己返回的错误）。 */
export function userError(message: string): string {
  if (currentLocale() === "zh-CN") return message;
  patterns ??= compile();
  for (const { key, re, names } of patterns) {
    const match = re.exec(message);
    // 占位符里也可能是一句认得出的错误（「第 2 条定时「x」：<原因>」）
    if (match) return t(key, Object.fromEntries(names.map((name, i) => [name, userError(match[i + 1])])));
  }
  return message;
}
